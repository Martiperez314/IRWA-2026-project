"""
Part 4: web analytics. In-memory storage with a star-schema design.

Fact tables (one row per event)            Dimension tables (who / what)
  requests  every HTTP request                sessions   physical session + visitor + user context
  queries   every new search                  products   the corpus (already in the search engine)
  clicks    every click on a result

Every fact row points to its session (session_id); queries and clicks also point to each other
(click.query_id) and to the product (click.pid). Everything is kept in memory while the app runs, as the
statement allows; /analytics/export downloads all tables as JSON.
"""
import ipaddress
import math
import json
import threading
import time
import uuid
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass, field
from datetime import datetime, timedelta
from typing import Dict, List, Optional

import httpagentparser

SESSION_TIMEOUT_S = 30 * 60   # a physical session ends after 30 minutes without requests
DWELL_MAX_S = 30 * 60          # a "return" later than this is not counted as dwell time
NOT_A_RETURN = {"doc_details", "track_dwell", "external_link", "static", "summary"}
# words that do not show a common goal: sharing only "men" does not make two queries the same mission
MISSION_IGNORE = {"men", "women", "boy", "girl", "kid", "unisex"}


# ----------------------------------------------------------------------------- tables
@dataclass
class Session:
    """Dimension: one physical session (a "sit-down") of one visitor, with its user context."""
    session_id: str
    visitor_id: str               # persistent cookie: the same browser across sessions
    start: float
    last_seen: float
    ip: str
    user_agent: str
    browser: str
    browser_version: str
    os: str
    device: str                   # desktop / mobile / tablet / bot
    country: Optional[str] = None
    city: Optional[str] = None
    simulated: bool = False       # traffic generated by simulate_traffic.py (labelled in the dashboard)
    n_requests: int = 0
    n_queries: int = 0
    n_clicks: int = 0


@dataclass
class Request:
    """Fact: one HTTP request."""
    request_id: int
    session_id: str
    timestamp: float
    method: str
    path: str
    endpoint: Optional[str]
    status: int
    duration_ms: float
    referrer: Optional[str]


@dataclass
class Query:
    """Fact: one new search typed by the user (changing page or filters does not create a new one)."""
    query_id: int
    session_id: str
    visitor_id: str
    timestamp: float
    text: str
    n_words: int                  # words typed
    terms: List[str]              # terms after our pre-processing
    n_results: int = 0
    mode: str = "all"             # all / partial (fallback) / none
    took_ms: float = 0.0
    order_in_session: int = 1     # 1st, 2nd... query of the session
    mission_id: int = 0           # logical session: queries with the same goal
    research_mission_id: int = 0  # missions that continue in later sessions of the same visitor
    filters_used: List[str] = field(default_factory=list)
    pages_viewed: int = 1


@dataclass
class Click:
    """Fact: one click on a result (to our details page or to the original website)."""
    click_id: int
    session_id: str
    query_id: Optional[int]
    pid: str
    rank: Optional[int]           # position of the result in the results page (1 = first)
    timestamp: float
    kind: str                     # "details" (our page) or "external" (original website)
    dwell_ms: Optional[float] = None
    dwell_source: Optional[str] = None  # "beacon" (time on the page) or "next_request"


# ----------------------------------------------------------------------------- store
class AnalyticsData:
    """In-memory persistence of the analytics tables."""

    def __init__(self, geo_lookup=None):
        self.sessions: Dict[str, Session] = {}
        self.requests: List[Request] = []
        self.queries: Dict[int, Query] = {}
        self.clicks: Dict[int, Click] = {}
        self.fact_clicks: Dict[str, int] = {}      # template table kept: clicks per product
        self._missions: Dict[int, set] = {}        # mission_id -> terms seen in the mission
        self._research_of: Dict[int, int] = {}
        self._last_click: Dict[str, int] = {}      # session_id -> last click without dwell time
        self._lock = threading.Lock()
        self._ids = Counter()
        self.geo_lookup = geo_lookup               # optional function ip -> (country, city)
        self.started = time.time()

    def _next_id(self, table):
        self._ids[table] += 1
        return self._ids[table]

    # ------------------------------------------------------------ sessions
    def get_or_create_session(self, cookie: dict, ip: str, user_agent: str, simulated=False,
                              force_new=False) -> Session:
        """
        Read the visitor/session ids from the Flask cookie (dict-like) and return the Session.
        A new physical session starts when there is no session yet or after SESSION_TIMEOUT_S idle.
        force_new: only for the traffic simulator, to start a new sit-down without waiting 30 minutes.
        """
        now = time.time()
        with self._lock:
            visitor_id = cookie.get("visitor_id") or uuid.uuid4().hex[:12]
            cookie["visitor_id"] = visitor_id
            session = self.sessions.get(cookie.get("session_id"))
            if session is None or now - session.last_seen > SESSION_TIMEOUT_S or (force_new and simulated):
                info = parse_user_agent(user_agent)
                country, city = self._geo(ip)
                session = Session(session_id=uuid.uuid4().hex[:12], visitor_id=visitor_id, start=now,
                                  last_seen=now, ip=ip, user_agent=user_agent or "", country=country,
                                  city=city, simulated=simulated, **info)
                self.sessions[session.session_id] = session
                cookie["session_id"] = session.session_id
            session.last_seen = now
            return session

    def _geo(self, ip):
        try:
            if ipaddress.ip_address(ip).is_private or ipaddress.ip_address(ip).is_loopback:
                return "Local network", "Local network"
        except ValueError:
            return None, None
        if self.geo_lookup:
            try:
                return self.geo_lookup(ip)
            except Exception:
                return None, None
        return None, None

    # ------------------------------------------------------------ requests
    def save_request(self, session_id, method, path, endpoint, status, duration_ms, referrer):
        with self._lock:
            now = time.time()
            self.requests.append(Request(self._next_id("request"), session_id, now, method, path,
                                         endpoint, status, round(duration_ms, 2), referrer))
            session = self.sessions.get(session_id)
            if session:
                session.n_requests += 1
            # dwell time fallback: the first page request after a click on a result, if the details
            # page could not send its beacon (the click itself and the beacon request are ignored)
            click_id = self._last_click.get(session_id)
            if click_id and endpoint not in NOT_A_RETURN:
                self._last_click.pop(session_id)
                click = self.clicks[click_id]
                if click.dwell_ms is None and now - click.timestamp < DWELL_MAX_S:
                    click.dwell_ms = round((now - click.timestamp) * 1000, 1)
                    click.dwell_source = "next_request"

    # ------------------------------------------------------------ queries
    def save_query(self, session: Session, text: str, terms: List[str]) -> int:
        """Store a new query and assign its mission (logical session). Returns the query id."""
        with self._lock:
            query_id = self._next_id("query")
            session.n_queries += 1
            mission_id, research_id = self._assign_mission(session, set(terms))
            self.queries[query_id] = Query(
                query_id=query_id, session_id=session.session_id, visitor_id=session.visitor_id,
                timestamp=time.time(), text=text, n_words=len(text.split()), terms=list(terms),
                order_in_session=session.n_queries, mission_id=mission_id,
                research_mission_id=research_id)
            return query_id

    def _assign_mission(self, session: Session, terms: set):
        """
        Missions: a query continues the mission of the previous query of the same session if they share
        at least one term ("men jeans" -> "men slim jeans"); otherwise it starts a new mission. Gender words
        are ignored ("men jeans" -> "men shoes" is a new mission).
        Research missions: a new mission continues an older mission of the same visitor from an EARLIER
        session if they share a term (same goal, another day).
        """
        terms = terms - MISSION_IGNORE
        previous = [q for q in self.queries.values() if q.session_id == session.session_id]
        if previous and terms & self._missions[previous[-1].mission_id]:
            mission_id = previous[-1].mission_id
            self._missions[mission_id] |= terms
            return mission_id, self._research_of[mission_id]
        mission_id = self._next_id("mission")
        self._missions[mission_id] = set(terms)
        research_id = mission_id
        older = [q for q in self.queries.values()
                 if q.visitor_id == session.visitor_id and q.session_id != session.session_id]
        for q in reversed(older):
            if terms & self._missions[q.mission_id]:
                research_id = self._research_of[q.mission_id]
                break
        self._research_of[mission_id] = research_id
        return mission_id, research_id

    def update_query(self, query_id, n_results=None, mode=None, took_ms=None, filters=None, new_page=False):
        with self._lock:
            q = self.queries.get(query_id)
            if not q:
                return
            if n_results is not None:
                q.n_results = n_results
            if mode is not None:
                q.mode = mode
            if took_ms is not None:
                q.took_ms = round(took_ms, 2)
            for f in filters or []:
                if f not in q.filters_used:
                    q.filters_used.append(f)
            if new_page:
                q.pages_viewed += 1

    # ------------------------------------------------------------ clicks
    def save_click(self, session_id, query_id, pid, rank, kind) -> int:
        with self._lock:
            click_id = self._next_id("click")
            self.clicks[click_id] = Click(click_id, session_id, query_id, pid, rank, time.time(), kind)
            self.fact_clicks[pid] = self.fact_clicks.get(pid, 0) + 1
            session = self.sessions.get(session_id)
            if session:
                session.n_clicks += 1
            if kind == "details":
                self._last_click[session_id] = click_id
            return click_id

    def save_dwell(self, click_id, session_id, dwell_ms):
        """Dwell time sent by the details page (time the page was visible before leaving)."""
        with self._lock:
            click = self.clicks.get(click_id)
            if not click or click.session_id != session_id or dwell_ms is None:
                return False
            if 0 < dwell_ms < DWELL_MAX_S * 1000:
                click.dwell_ms = round(float(dwell_ms), 1)
                click.dwell_source = "beacon"
                self._last_click.pop(session_id, None)
                return True
            return False

    # ------------------------------------------------------------ export
    def export(self):
        """All tables as plain dicts (for /analytics/export and for the report)."""
        with self._lock:
            return {
                "generated_at": datetime.now().isoformat(timespec="seconds"),
                "sessions": [asdict(s) for s in self.sessions.values()],
                "requests": [asdict(r) for r in self.requests],
                "queries": [asdict(q) for q in self.queries.values()],
                "clicks": [asdict(c) for c in self.clicks.values()],
            }

    # ------------------------------------------------------------ dashboard
    def dashboard_data(self, titles=None, include_simulated=True):
        """
        Key indicators and the data of every chart of the dashboard.
        titles: function pid -> product title (to label the most clicked products).
        """
        with self._lock:
            sessions = [s for s in self.sessions.values() if include_simulated or not s.simulated]
            ids = {s.session_id for s in sessions}
            requests = [r for r in self.requests if r.session_id in ids]
            queries = [q for q in self.queries.values() if q.session_id in ids]
            clicks = [c for c in self.clicks.values() if c.session_id in ids]

        result_clicks = [c for c in clicks if c.query_id is not None]
        clicked_queries = {c.query_id for c in result_clicks}
        dwell = [c.dwell_ms / 1000 for c in clicks if c.dwell_ms is not None]
        ranks = [c.rank for c in result_clicks if c.rank]
        first_rank = {}  # best (lowest) clicked rank of each query, for the MRR
        for c in result_clicks:
            if c.rank:
                first_rank[c.query_id] = min(c.rank, first_rank.get(c.query_id, c.rank))
        missions = {q.mission_id for q in queries}
        research = Counter(q.research_mission_id for q in queries)
        multi_session_research = sum(
            1 for rid in research if len({q.session_id for q in queries if q.research_mission_id == rid}) > 1)

        def pct(a, b):
            return round(100 * a / b, 1) if b else 0.0

        def avg(values, digits=2):
            return round(sum(values) / len(values), digits) if values else 0.0

        kpis = {
            "visitors": len({s.visitor_id for s in sessions}),
            "sessions": len(sessions),
            "requests": len(requests),
            "queries": len(queries),
            "clicks": len(clicks),
            "ctr": pct(len(clicked_queries), len(queries)),            # % of queries with >= 1 click
            "zero_results": pct(sum(q.n_results == 0 for q in queries), len(queries)),
            "fallback": pct(sum(q.mode == "partial" for q in queries), len(queries)),
            "avg_clicked_rank": avg(ranks, 1),
            "mrr": round(sum(1 / r for r in first_rank.values()) / len(queries), 3) if queries else 0.0,
            "avg_dwell_s": avg(dwell, 1),
            "avg_terms": avg([q.n_words for q in queries], 1),
            "queries_per_session": avg([s.n_queries for s in sessions], 1),
            "missions": len(missions),
            "queries_per_mission": round(len(queries) / len(missions), 2) if missions else 0.0,
            "research_missions": multi_session_research,
            "avg_response_ms": avg([q.took_ms for q in queries], 1),
            "p95_response_ms": round(sorted(q.took_ms for q in queries)[math.ceil(0.95 * len(queries)) - 1], 1)
            if queries else 0.0,  # nearest-rank percentile
            "simulated_sessions": sum(s.simulated for s in sessions),
        }

        # activity over time: the time step adapts to the period covered by the data
        # (per minute if it is under 2 hours, per hour if under 2 days, otherwise per day)
        hours = Counter(datetime.fromtimestamp(q.timestamp).hour for q in queries)
        times = [r.timestamp for r in requests] + [q.timestamp for q in queries]
        span = (max(times) - min(times)) if times else 0
        step, fmt = (("minute", "%H:%M") if span < 2 * 3600 else
                     ("hour", "%m-%d %H:00") if span < 2 * 86400 else ("day", "%Y-%m-%d"))
        days = Counter(datetime.fromtimestamp(r.timestamp).strftime(fmt) for r in requests)
        query_days = Counter(datetime.fromtimestamp(q.timestamp).strftime(fmt) for q in queries)
        day_labels = _time_steps(min(times), max(times), step, fmt) if times else []  # empty steps count as 0

        # queries and terms
        top_queries = Counter(q.text.strip().lower() for q in queries).most_common(10)
        top_terms = Counter(t for q in queries for t in q.terms).most_common(15)
        length_dist = Counter(min(q.n_words, 8) for q in queries)

        # clicks by position (position bias) and dwell time distribution
        rank_dist = Counter(min(r, 21) for r in ranks)
        dwell_bins = [(0, 5), (5, 15), (15, 30), (30, 60), (60, 120), (120, 300), (300, 10 ** 9)]
        dwell_labels = ["<5 s", "5-15 s", "15-30 s", "30-60 s", "1-2 min", "2-5 min", ">5 min"]
        dwell_dist = [sum(lo <= d < hi for d in dwell) for lo, hi in dwell_bins]

        # most clicked products, with the average rank and dwell time of their clicks
        by_pid = defaultdict(list)
        for c in result_clicks:
            by_pid[c.pid].append(c)
        top_products = sorted(by_pid.items(), key=lambda kv: -len(kv[1]))[:10]
        top_products = [{"pid": pid, "title": titles(pid) if titles else pid, "clicks": len(cs),
                         "avg_rank": avg([c.rank for c in cs if c.rank], 1),
                         "avg_dwell_s": avg([c.dwell_ms / 1000 for c in cs if c.dwell_ms], 1)}
                        for pid, cs in top_products]

        # user context
        browsers = Counter(s.browser for s in sessions)
        oss = Counter(s.os for s in sessions)
        devices = Counter(s.device for s in sessions)
        countries = Counter(s.country or "Unknown" for s in sessions)

        # content gaps: queries with no results or answered with the fallback
        gaps = Counter((q.text.strip().lower(), q.mode) for q in queries if q.mode != "all" or q.n_results == 0)
        filters = Counter(f.split(":")[0] for q in queries for f in q.filters_used)
        pages = Counter(r.endpoint or r.path for r in requests)

        return {
            "kpis": kpis,
            "hours": {"labels": list(range(24)), "values": [hours.get(h, 0) for h in range(24)]},
            "days": {"labels": day_labels, "requests": [days.get(d, 0) for d in day_labels],
                     "queries": [query_days.get(d, 0) for d in day_labels], "step": step},
            "top_queries": {"labels": [q for q, _ in top_queries], "values": [n for _, n in top_queries]},
            "top_terms": {"labels": [t for t, _ in top_terms], "values": [n for _, n in top_terms]},
            "query_length": {"labels": [str(i) if i < 8 else "8+" for i in range(1, 9)],
                             "values": [length_dist.get(i, 0) for i in range(1, 9)]},
            "rank_clicks": {"labels": [str(i) if i < 21 else "21+" for i in range(1, 22)],
                            "values": [rank_dist.get(i, 0) for i in range(1, 22)]},
            "dwell": {"labels": dwell_labels, "values": dwell_dist},
            "top_products": top_products,
            "browsers": _pairs(browsers), "os": _pairs(oss), "devices": _pairs(devices),
            "countries": _pairs(countries),
            "gaps": [{"query": q, "mode": m, "count": n} for (q, m), n in gaps.most_common(10)],
            "filters": _pairs(filters),
            "pages": _pairs(pages),
            "sessions_queries": _ordered(Counter(min(s.n_queries, 10) for s in sessions), range(0, 11), last="10+"),
        }


def _time_steps(start, end, step, fmt):
    """Every minute / hour / day between two timestamps, as labels (so idle periods show as 0)."""
    first = datetime.fromtimestamp(start)
    first = first.replace(second=0, microsecond=0)
    if step in ("hour", "day"):
        first = first.replace(minute=0)
    if step == "day":
        first = first.replace(hour=0)
    delta = timedelta(minutes=1) if step == "minute" else timedelta(hours=1) if step == "hour" else timedelta(days=1)
    labels, current, last = [], first, datetime.fromtimestamp(end)
    while current <= last:
        labels.append(current.strftime(fmt))
        current += delta
    return labels


def _ordered(counter, keys, last=None):
    """Counts in a fixed order (0, 1, 2...) for charts whose x axis is a number."""
    keys = list(keys)
    labels = [str(k) for k in keys]
    if last:
        labels[-1] = last
    return {"labels": labels, "values": [counter.get(k, 0) for k in keys]}


def _pairs(counter):
    items = counter.most_common()
    return {"labels": [str(k) for k, _ in items], "values": [v for _, v in items]}


def parse_user_agent(user_agent: str) -> dict:
    """Browser, OS and device type from the User-Agent header (httpagentparser + simple rules)."""
    ua = user_agent or ""
    info = httpagentparser.detect(ua) if ua else {}
    browser = info.get("browser", {}) or {}
    os_info = info.get("os", {}) or {}
    platform = info.get("platform", {}) or {}
    low = ua.lower()
    if info.get("bot") or any(w in low for w in ("bot", "spider", "crawl", "curl", "python-urllib", "wget")):
        device = "bot"
    elif "ipad" in low or "tablet" in low:
        device = "tablet"
    elif "mobi" in low or "iphone" in low or "android" in low:
        device = "mobile"
    else:
        device = "desktop"
    os_name = os_info.get("name") or platform.get("name") or "Unknown"
    if os_name == "Macintosh":
        os_name = "macOS"
    return {"browser": browser.get("name") or "Unknown", "browser_version": browser.get("version") or "",
            "os": os_name, "device": device}


class ClickedDoc:
    """Kept from the template (used by older code); the dashboard now uses dashboard_data()."""

    def __init__(self, doc_id, description, counter):
        self.doc_id = doc_id
        self.description = description
        self.counter = counter

    def to_json(self):
        return self.__dict__

    def __str__(self):
        return json.dumps(self.__dict__)
